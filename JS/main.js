function renderLibraryGrid(gamesArray) {
  const gameGrid = document.getElementById("gameGrid");
  if (!gameGrid) return;

  const list = Array.isArray(gamesArray) ? gamesArray : [];
  window.__nxGridSource = list;

  // Tear down previous virtualizer
  if (window.__nxVirtual && typeof window.__nxVirtual.destroy === "function") {
    try { window.__nxVirtual.destroy(); } catch (e) {}
  }
  gameGrid.innerHTML = "";
  const oldBtn = document.getElementById("nx-load-more");
  if (oldBtn) oldBtn.remove();

  if (!list.length) return;

  // Virtual window: only cards near the viewport exist in the DOM
  const GAP = 12;
  const OVERSCAN = 2; // extra rows above/below
  const TARGET_COLS = 4; // preferred columns on desktop
  const MAX_CARD = 148; // keep cards smaller / square

  const scroller = gameGrid.parentElement || document.documentElement;
  const spacer = document.createElement("div");
  spacer.id = "nx-virtual-spacer";
  spacer.style.cssText = "position:relative;width:100%;";
  const windowEl = document.createElement("div");
  windowEl.id = "nx-virtual-window";
  windowEl.style.cssText = "position:absolute;left:0;right:0;top:0;will-change:transform;";
  spacer.appendChild(windowEl);
  gameGrid.appendChild(spacer);

  // Override grid layout while virtualizing — cards positioned absolutely in rows
  gameGrid.style.display = "block";
  gameGrid.style.minHeight = "0";
  gameGrid.style.overflow = "hidden";
  gameGrid.style.boxSizing = "border-box";
  gameGrid.style.width = "100%";

  let cols = 1;
  let rowH = MAX_CARD + GAP;
  let totalRows = 1;
  let raf = 0;
  let lastStart = -1;
  let lastEnd = -1;
  const cardPool = new Map(); // id -> element

  function measure() {
    // clientWidth already excludes scrollbar; subtract a little so the right column is never clipped
    const raw = Math.max(gameGrid.clientWidth || gameGrid.offsetWidth || 600, 200);
    const width = Math.max(raw - 8, 180);
    if (width < 520) cols = 2;
    else if (width < 760) cols = 3;
    else cols = TARGET_COLS;
    // Slightly smaller than full width so they breathe and don't clip
    const colW = (width - GAP * (cols - 1)) / cols;
    window.__nxCardSize = Math.max(96, colW * 0.92);
    totalRows = Math.ceil(list.length / cols) || 1;
    rowH = window.__nxCardSize + GAP;
    // Center the row of smaller cards in the available width
    window.__nxXOff = Math.max(0, (raw - (cols * window.__nxCardSize + (cols - 1) * GAP)) / 2);
    spacer.style.height = (totalRows * rowH) + "px";
  }

  function makeCard(game) {
    const card = document.createElement("div");
    card.className = "game-card";
    card.setAttribute("data-game-id", game.id);
    card.style.cssText = "position:absolute;box-sizing:border-box;margin:0;overflow:hidden;border-radius:14px;";

    const title = String(game.title || "Game");
    if (game.image) {
      const img = document.createElement("img");
      img.className = "game-card-img";
      img.alt = "";
      img.loading = "lazy";
      img.decoding = "async";
      img.style.cssText = "width:100%;height:100%;object-fit:cover;position:absolute;inset:0;";
      img.src = String(game.image);
      card.appendChild(img);
    } else {
      const ph = document.createElement("div");
      ph.className = "game-card-img-placeholder";
      ph.style.cssText = "position:absolute;inset:0;display:flex;align-items:center;justify-content:center;background:linear-gradient(135deg,#2a1a40,#12091c);";
      const sp = document.createElement("span");
      sp.textContent = title.substring(0, 2).toUpperCase();
      ph.appendChild(sp);
      card.appendChild(ph);
    }
    const h3 = document.createElement("h3");
    h3.textContent = title;
    h3.style.cssText = "position:absolute;left:0;right:0;top:0;bottom:0;z-index:3;margin:0;padding:10px 12px;display:flex;align-items:center;justify-content:center;font-size:0.82rem;font-weight:800;text-align:center;color:#fff;line-height:1.2;letter-spacing:0.02em;text-shadow:0 1px 3px #000,0 0 10px #000,0 2px 8px #000;background:rgba(0,0,0,0.35);box-sizing:border-box;";
    card.appendChild(h3);
    const desc = document.createElement("div");
    desc.className = "game-desc-overlay";
    desc.textContent = String(game.desc || "");
    card.appendChild(desc);
    card.onclick = function () { launchGame(game.id); };
    return card;
  }

  function getScrollParent(el) {
    let p = el.parentElement;
    while (p && p !== document.body) {
      const st = getComputedStyle(p);
      const oy = st.overflowY;
      if (oy === "auto" || oy === "scroll" || oy === "overlay") return p;
      p = p.parentElement;
    }
    return window;
  }

  const scrollRoot = getScrollParent(gameGrid);

  function scrollTop() {
    return scrollRoot === window
      ? (window.scrollY || document.documentElement.scrollTop || 0)
      : scrollRoot.scrollTop;
  }
  function viewHeight() {
    return scrollRoot === window ? window.innerHeight : scrollRoot.clientHeight;
  }
  function gridOffsetTop() {
    const rect = spacer.getBoundingClientRect();
    if (scrollRoot === window) return rect.top + scrollTop();
    const rootRect = scrollRoot.getBoundingClientRect();
    return rect.top - rootRect.top + scrollRoot.scrollTop;
  }

  function paint() {
    raf = 0;
    measure();
    const width = Math.max(gameGrid.clientWidth || 600, 200);
    const size = window.__nxCardSize || 140;
    const xOff = window.__nxXOff || 0;
    const top = scrollTop();
    const offset = gridOffsetTop();
    const relTop = Math.max(0, top - offset);
    const startRow = Math.max(0, Math.floor(relTop / rowH) - OVERSCAN);
    const endRow = Math.min(totalRows, Math.ceil((relTop + viewHeight()) / rowH) + OVERSCAN);
    if (startRow === lastStart && endRow === lastEnd && windowEl.childElementCount) return;
    lastStart = startRow;
    lastEnd = endRow;

    const needed = new Set();
    for (let row = startRow; row < endRow; row++) {
      for (let c = 0; c < cols; c++) {
        const idx = row * cols + c;
        if (idx >= list.length) break;
        const game = list[idx];
        if (!game) continue;
        needed.add(String(game.id));
        let card = cardPool.get(String(game.id));
        if (!card) {
          card = makeCard(game);
          cardPool.set(String(game.id), card);
          windowEl.appendChild(card);
        }
        card.style.width = size + "px";
        card.style.height = size + "px";
        card.style.transform = "translate(" + (xOff + c * (size + GAP)) + "px," + (row * rowH) + "px)";
        card.style.display = "";
      }
    }
    // recycle offscreen
    cardPool.forEach(function (card, id) {
      if (!needed.has(id)) {
        card.remove();
        cardPool.delete(id);
      }
    });
  }

  function onScroll() {
    if (raf) return;
    raf = requestAnimationFrame(paint);
  }
  function onResize() {
    lastStart = -1;
    onScroll();
  }

  if (scrollRoot === window) {
    window.addEventListener("scroll", onScroll, { passive: true });
  } else {
    scrollRoot.addEventListener("scroll", onScroll, { passive: true });
  }
  window.addEventListener("resize", onResize, { passive: true });

  paint();

  window.__nxVirtual = {
    destroy: function () {
      if (scrollRoot === window) window.removeEventListener("scroll", onScroll);
      else scrollRoot.removeEventListener("scroll", onScroll);
      window.removeEventListener("resize", onResize);
      if (raf) cancelAnimationFrame(raf);
      cardPool.clear();
      gameGrid.style.display = "";
    }
  };
}


